-- Rice AI PostgreSQL schema for Neon
-- Run this file against the database created by Neon.
-- Passwords are never stored as plaintext. The application stores bcrypt hashes.

CREATE TABLE IF NOT EXISTS users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(50) UNIQUE,
    password varchar(255) NOT NULL,
    first_name varchar(100),
    last_name varchar(100),
    email varchar(150),
    phone varchar(20),
    address text,
    role varchar(20) CHECK (role IN ('farmer', 'expert', 'admin')) DEFAULT 'farmer',
    banned smallint NOT NULL DEFAULT 0,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    profile_image varchar(255)
);

CREATE TABLE IF NOT EXISTS articles (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(255) NOT NULL,
    description text,
    category varchar(30) DEFAULT 'disease' CHECK (category IN ('disease', 'pest', 'fertilizer', 'care')),
    content text,
    thumbnail varchar(255),
    views integer NOT NULL DEFAULT 0,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS history (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer REFERENCES users(id) ON DELETE SET NULL,
    location_name varchar(255),
    disease varchar(100),
    confidence numeric(5, 2),
    variety_code varchar(50),
    latitude double precision,
    longitude double precision,
    image_base64 text,
    status varchar(30) NOT NULL DEFAULT 'completed'
        CHECK (status IN ('completed', 'pending_expert', 'reviewed')),
    timestamp timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    weather varchar(100),
    is_verified smallint NOT NULL DEFAULT 0,
    expert_result varchar(100),
    expert_comment text,
    expert_id integer REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS messages (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_name varchar(100) NOT NULL,
    phone varchar(20),
    subject varchar(100),
    message text NOT NULL,
    image_path varchar(255),
    is_read smallint NOT NULL DEFAULT 0,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    source varchar(50) DEFAULT 'general'
);

CREATE TABLE IF NOT EXISTS notifications (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    history_id integer REFERENCES history(id) ON DELETE SET NULL,
    title varchar(255) NOT NULL,
    message text,
    is_read smallint NOT NULL DEFAULT 0,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS password_resets (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token varchar(255) NOT NULL,
    type varchar(10) NOT NULL CHECK (type IN ('phone', 'email')),
    expires_at timestamp NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS expert_reviews (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    history_id integer NOT NULL REFERENCES history(id) ON DELETE CASCADE,
    expert_id integer REFERENCES users(id) ON DELETE SET NULL,
    final_disease varchar(100) NOT NULL,
    comment text,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_history_user_id ON history(user_id);
CREATE INDEX IF NOT EXISTS idx_history_timestamp ON history(timestamp);
CREATE INDEX IF NOT EXISTS idx_notifications_user_id ON notifications(user_id);
CREATE INDEX IF NOT EXISTS idx_password_resets_user_id ON password_resets(user_id);

